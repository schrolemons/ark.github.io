import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto((process.env.TEST_URL || 'http://127.0.0.1:4321/') + '#more');
await page.waitForTimeout(4000);
await page.locator('[data-more-page]').waitFor();
assert.ok(await page.getByText('PROJECT ARCHIVE', { exact: true }).count() >= 1);
assert.ok(await page.getByText('SYSTEM STATUS', { exact: true }).count() >= 1);
assert.equal(await page.locator('[data-more-page] article').count(), 3);
for (const stat of ['project-records', 'operator-records', 'world-entries', 'information-records', 'navigation-sections']) {
  assert.match(await page.locator(`[data-stat="${stat}"]`).innerText(), /^\d{2}$/);
}
await page.screenshot({ path: '.screens/more-page-final.png' });
await page.getByRole('link', { name: '模板仓库 - REPOSITORY' }).click();
await page.waitForURL('**/#more/repository');
assert.equal(await page.getByText('SELECTED // REPOSITORY', { exact: true }).count(), 1);
await page.mouse.wheel(0, 800);
await page.waitForTimeout(1000);
assert.equal(await page.getByText('END OF ARCHIVE', { exact: true }).count(), 1);
await page.screenshot({ path: '.screens/more-footer-final.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto((process.env.TEST_URL || 'http://127.0.0.1:4321/') + '#more/author_profile');
await page.waitForTimeout(2500);
const bounds = await page.locator('[data-more-page] main').boundingBox();
assert.ok(bounds && bounds.width <= 390);
assert.equal(await page.getByText('SELECTED // AUTHOR PROFILE', { exact: true }).count(), 1);
await page.screenshot({ path: '.screens/more-mobile-final.png' });
assert.deepEqual(errors, []);
console.log('PASS More archive desktop, deep link, footer and mobile layout');
await browser.close();
